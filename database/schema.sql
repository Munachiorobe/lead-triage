-- 3. Interactions
<create table public.interactions (
  id bigint generated by default as identity not null,
  created_at timestamp with time zone not null default now(),
  lead_id bigint not null,
  interaction_type text not null,
  summary text not null,
  created_by text not null,
  counselors text not null default ''::text,
  constraint interactions_pkey primary key (id),
  constraint interactions_lead_id_fkey foreign KEY (lead_id) references femtorpath_leads (id) on delete CASCADE
) TABLESPACE pg_default;

create trigger trg_first_contact
after INSERT on interactions for EACH row
execute FUNCTION set_first_contact ();>

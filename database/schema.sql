-- 1. Counselors
<create table public.counselors (
  id bigint generated by default as identity not null,
  created_at timestamp with time zone not null default now(),
  name text not null,
  email text not null,
  whatsapp_number text not null,
  active_lead_count bigint not null default '0'::bigint,
  coverage_area text null,
  is_active boolean null default true,
  constraint counselors_pkey primary key (id)
) TABLESPACE pg_default;>

-- 2. Leads
<create table public.femtorpath_leads (
  id bigint generated by default as identity not null,
  created_at timestamp with time zone not null default now(),
  full_name text not null default ''::text,
  phone_number text null,
  email text null,
  source text null,
  program_interest text null,
  destination_country text null,
  budget_range text null,
  status text null default 'New'::text,
  lead_score bigint null,
  ai_next_action text null,
  assigned_counselor text null,
  last_contacted_at timestamp with time zone null,
  next_followup_date date null,
  notes text null,
  last_reminder_sent date null,
  study_level text null,
  intake text null,
  funds_status text null,
  consent_given boolean null default false,
  consent_at timestamp with time zone null,
  priority text null,
  score_reason text null,
  ai_draft_message text null,
